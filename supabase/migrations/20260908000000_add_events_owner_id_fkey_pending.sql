-- v2 M4 (Issue #375, In Scope #1 / decisions.md "PO 判断: v2 の DB 方針" P5).
--
-- Every FK from a product table to auth.users(id) was declared without an
-- explicit ON DELETE clause (Postgres default: NO ACTION), except
-- catalog_creators.user_id (ON DELETE CASCADE, 20260822000200). oracle-
-- database.md §7 point 2 records this as an unintentional inconsistency,
-- not a decided policy - there is no account-deletion feature yet, so
-- nothing has ever exercised it.
--
-- decisions.md's P5 PO decision fixes the policy now, independent of when
-- an actual account-deletion feature ships (deleting a Supabase Auth user
-- directly, e.g. via the Admin API, already exercises these FKs today even
-- without a product-level "delete my account" UI):
--
--   shared catalog data (Event / Occurrence)      -> kept
--   personal data (participation / invitation /
--     personal schedule / ticket opportunity state) -> deleted
--
-- events.owner_id -> ON DELETE NO ACTION, made explicit rather than
-- changed. "残す" (kept) means the Event row must never be silently
-- destroyed or silently orphaned as a side effect of deleting a user - and
-- owner_id is NOT NULL with no product-approved "ownerless event" state
-- (product-rules.md "Ownership": every Event has an owner; owner transfer
-- is not a supported operation). ON DELETE NO ACTION preserves the row
-- unconditionally because the auth.users delete itself is refused while it
-- would orphan an Event; nothing about the Event ever changes. This needs
-- no new product state: deleting a catalog-creator's auth user while they
-- still own Events simply fails until those Events are handled first -
-- product-rules.md's "Deletion" section already gives the owner (or an
-- operator) a real path to do that.
--
-- The FK was declared inline (`references auth.users (id)` with no
-- explicit constraint name), so it carries Postgres's default autogenerated
-- name (`events_owner_id_fkey`) - confirmed against the local Supabase
-- instance (pg_constraint) rather than assumed. Postgres has no
-- `ALTER ... ALTER CONSTRAINT` for changing a FK's ON DELETE action in
-- place, so it must be dropped and recreated with the same name and
-- target, adding only the ON DELETE clause.
--
-- Legacy safety: this only changes what happens when a referenced
-- auth.users row is deleted. Legacy has no account-deletion path today, so
-- no existing legacy behavior observes this change; it only takes effect
-- once something starts deleting auth.users rows.
--
-- === PRODUCTION LOCK SAFETY (review finding on PR #378, round 2) ===
--
-- legacy shares this schema with a live production database, and tables
-- such as personal_schedule_entries / occurrence_participations already
-- hold real, growing row counts there - unlike the near-empty local dev
-- database this migration is developed against.
--
-- A plain `alter table t drop constraint old, add constraint old foreign
-- key (...) references auth.users (id) on delete cascade` recreates the FK
-- in one ALTER TABLE. Postgres validates every existing row against the
-- new constraint before that statement returns, and it does so while
-- holding ACCESS EXCLUSIVE on the table for the statement's *full*
-- duration. This migration therefore only performs step 1 of the standard
-- Postgres "expand/validate" pattern for changing a FK's ON DELETE action
-- without a long-held ACCESS EXCLUSIVE lock:
--
--   1. (this file + 20260908000001..000005) add each new FK as NOT VALID,
--      under a temporary `<name>_pending` constraint name, leaving the
--      existing (already validated) constraint in place and fully
--      enforced throughout.
--   2. (20260908000010) VALIDATE CONSTRAINT the pending FKs.
--   3. (20260908000020..000025) drop the old constraint and rename the
--      pending one to the final name.
--
-- Round 1 of this review combined all seven tables' step-1 ADD CONSTRAINTs
-- into a single migration file (a single transaction). Round 2 found that
-- combination itself lock-unsafe: Postgres holds every lock a transaction
-- has acquired until the *transaction* ends, not until the statement ends.
-- If a later table in that combined transaction (e.g.
-- personal_schedule_entries) was busy with a long-running production
-- transaction, the ACCESS EXCLUSIVE lock already taken on an *earlier*
-- table (events) stayed held for the entire wait - blocking every read and
-- write against events too, and queuing behind it any further lock
-- requests against events. So one busy table could stall multiple
-- unrelated tables for an unbounded time; "catalog operation x 7, so it's
-- fast" was not a safe conclusion.
--
-- Fix: step 1 is now one migration file per distinct table (this file
-- covers events; 20260908000001..000005 cover the other five product
-- tables from the list above - occurrence_invitations has two FKs but they
-- share one file/transaction since both target the same table, so there is
-- no second table whose lock could be held hostage). Each file is its own
-- transaction, so no table's lock can ever be held hostage behind another
-- table's contention.
--
-- `set local lock_timeout` bounds how long this statement will wait to
-- acquire that ACCESS EXCLUSIVE lock before giving up, rather than queuing
-- indefinitely behind whatever currently holds or is queued ahead of it on
-- this table. 5s is chosen because ADD CONSTRAINT ... NOT VALID does not
-- scan existing rows (that is the whole point of NOT VALID), so under
-- normal conditions this lock is pure catalog bookkeeping and is granted
-- in milliseconds; a wait of several seconds already means a real
-- conflicting transaction is in progress, not ordinary scheduling jitter -
-- 5s is long enough to absorb that jitter (e.g. a pooled connection
-- briefly holding a lock while it finishes an unrelated fast statement)
-- without failing spuriously, while still bounding the worst case to
-- something an operator notices and can retry within the same maintenance
-- window, instead of stalling production for however long the conflicting
-- transaction takes to finish.
--
-- If this statement fails with `55P03 lock not available`: a long-running
-- transaction is currently holding a conflicting lock on the target table.
-- No partial state is left behind - the failed statement's transaction
-- rolls back automatically, and this migration is not recorded as
-- applied - so the operator can simply wait a short while for the
-- conflicting transaction to finish and re-run `supabase db push`;
-- retrying is always safe and has no side effects if it fails again.
--
-- No cross-file ordering dependency on any other migration in this
-- repository, and no Vercel deploy depends on this migration (application
-- code never reads pg_constraint), so this is `post-deploy-safe` per
-- docs/architecture/runtime-stack.md's ordering fence. This file and the
-- rest of the expand/validate/swap set should be applied together in one
-- maintenance pass, but the intermediate states between them are all valid
-- and safe to leave applied for a while if needed (two FKs enforcing the
-- same reference is redundant but harmless).
-- Wrapped in an explicit transaction. The Supabase migration runner is not
-- guaranteed to wrap a file's statements in one (20260821000100 wraps for
-- the same reason), and `set local` has no effect outside a transaction
-- block - it would emit a warning and silently leave lock_timeout at its
-- default, removing the bound this file relies on. Wrapping explicitly
-- makes the bound hold regardless of runner behavior.
begin;

set local lock_timeout = '5s';

alter table public.events
  add constraint events_owner_id_fkey_pending
    foreign key (owner_id) references auth.users (id) on delete no action
    not valid;

commit;
